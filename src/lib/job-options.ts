//    небезпечною людиною; довірити дитину/дім/безпеку незнайомцю без
//    посередника — ризик іншого роду);
// 2) робота вимагає ліцензії/регуляторного статусу, якого в одноосібного
//    ФОП фізично бути не може (банківська каса, обмін валют, ломбард —
//    ліцензія НБУ/фінустанови);
// 3) категорія вакансії — типове прикриття для вербування в трафікінг/
//    секс-індустрію під легальним на вигляд оголошенням (аніматор/
//    масажист "у готель за кордоном" — класична схема). Верифікована
//    юрособа (готель, SPA-мережа) значно важче підробити, ніж ФОП чи
//    анонімний акаунт, тож саме тут піднімаємо поріг;
// 4) судно (палубна/машинна команда, судновий сервіс, портове
//    господарство) — це завжди актив юрособи (судновласник, портовий
//    оператор, крюїнгова агенція), одноосібний ФОП фізично не може бути
//    роботодавцем на судні чи в порту. Виняток у цій категорії —
//    промислове рибальство (maritime_fishing_aquaculture), там ФОП
//    дозволені окремою логікою — див. checkFishingActivityMatch.
// Хто не хоче йти через агенцію/ліцензовану установу — може шукати на
// інших майданчиках на свій ризик, тут це свідомо не підтримується.
const AGENCY_ONLY_PAIRS = new Set([
  "education:nannies",
  "education:governess",
  "education:tutors",
  "drivers:personal_driver",
  "security:personal_security",
  "service_staff:private_household_staff",
  "accounting:cash_operations",
  "hospitality:horeca_animators_masseurs",
  "maritime_transport:maritime_deck_crew",
  "maritime_transport:maritime_engine_crew",
  "maritime_transport:maritime_service_catering",
  "maritime_transport:maritime_port_logistics",
]);

export function requiresAgencyVerification(
  category: string,
  subcategory: string | null | undefined,
): boolean {
  return !!subcategory && AGENCY_ONLY_PAIRS.has(`${category}:${subcategory}`);
}

// category:subcategory для промислового рибальства — див. коментар над
// AGENCY_ONLY_PAIRS (виняток №4) і checkFishingActivityMatch-логіку в
// route.ts / matchesLicensedFishingActivity у trust-gate.ts.
export function isFishingSubcategory(
  category: string,
  subcategory: string | null | undefined,
): boolean {
  return (
    category === "maritime_transport" &&
    subcategory === "maritime_fishing_aquaculture"
  );
}

// Пари category:subcategory, де достатньо звичайної верифікації (ЄДРПОУ
// або ІПН/РНОКПП) — на відміну від AGENCY_ONLY_PAIRS, тут ФОП дозволений,
// якщо верифікований. Приклад: аптека цілком легально може бути ФОП з
// ліцензією на фармацевтичну діяльність — тут ризик не "приватна особа
// замість структури", а просто "потрібна підтверджена ліцензована
// діяльність, а не анонім".
const VERIFIED_ONLY_PAIRS = new Set(["medical:pharmacy"]);

export function requiresVerificationOnly(
  category: string,
  subcategory: string | null | undefined,
): boolean {
  return !!subcategory && VERIFIED_ONLY_PAIRS.has(`${category}:${subcategory}`);
}

// Пари category:subcategory, які по суті є державними органами/службами,
// хоча самі живуть не в категорії "government" — санепідслужба та
// Держпродспоживслужба зазначені в категорії "медицина" (бо кандидати
// шукають їх поруч із мед. вакансіями), але як роботодавець це той самий
// клас ризику, що й будь-яка держструктура: анонім/ФОП не повинен
// публікувати вакансію нібито від імені держоргану. Гейт для них — той
// самий, що і на всю категорію "government" (лише верифікована юрособа).
const GOVERNMENT_AUTHORITY_PAIRS = new Set([
  "medical:sanitary_epidemiological_service",
]);

export function isGovernmentAuthorityRole(
  category: string,
  subcategory: string | null | undefined,
): boolean {
  return (
    category === "government" ||
    (!!subcategory &&
      GOVERNMENT_AUTHORITY_PAIRS.has(`${category}:${subcategory}`))
  );
}

// М'яка (не блокуюча) підказка для форми: якщо роботодавець публікує
// вакансію в категорії "Військові професії", але текст описує типову
// цивільну роль харчоблоку/їдальні в тиловій установі (шпиталь, навчальний
// заклад) — це часто вільнонаймана цивільна посада, а не військовослужбовець
// (на відміну від "військового кухаря" в бойовому підрозділі, який завжди
// в/с — див. підкатегорію technical_soldier). Ми не можемо і не повинні
// вирішувати це автоматично (в/ч сама знає, хто саме їй потрібен), тому
// лише підказуємо — рішення й вибір категорії лишається за роботодавцем.
const MILITARY_CATERING_INSTITUTION_KEYWORDS = [
  "шпитал", // шпиталь/шпиталю/шпиталі/шпитальний — корінь без закінчення,
  "госпітал", // щоб покривати всі відмінки одразу (типова помилка була
  "лазарет", // саме тут: "шпиталь" не збігався з "шпиталю" в описі)
  "навчальн",
  "коледж",
  "ліцей",
  "академі",
  "училищ",
  "інститут",
];

const CATERING_ROLE_KEYWORDS = [
  "кухар",
  "кухон",
  "харчоблок",
  "їдальн",
  "буфет",
  "роздавальник",
  "дієт",
];

export function suggestsCivilianCateringInMilitaryCategory(
  title: string,
  description: string,
): boolean {
  const text = `${title} ${description}`.toLowerCase();
  const hasInstitutionKeyword = MILITARY_CATERING_INSTITUTION_KEYWORDS.some(
    (kw) => text.includes(kw),
  );
  const hasCateringRoleKeyword = CATERING_ROLE_KEYWORDS.some((kw) =>
    text.includes(kw),
  );
  return hasInstitutionKeyword && hasCateringRoleKeyword;
}
